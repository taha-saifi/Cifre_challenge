#!/usr/bin/env python3
"""Derive a readable presentation view from the full canonical KG.

Why this exists
---------------
The brief (§11) suggests a graph of 15-30 nodes and 20-50 relations, and says plainly
that what matters is not the graph's sophistication but the ability to explain what it
captures and what it does not. The canonical KG has 1956 nodes and 2123 edges -- correct
for audit, unreadable on a slide.

This is NOT a second knowledge graph. It is a projection of the existing one, produced
by a rule rather than by hand-picking, so that every node and edge on the slide can be
traced back to the same `source_id` + `evidence` as in the full graph.

The rule has one idea: a score is not an entity.
  - Predicates whose object is a literal value (a CVSS score, a date, a probability)
    become ATTRIBUTES of the CVE node. Modelling "9.8" as a node shared between three
    CVEs is what inflates the node count without adding meaning.
  - Predicates whose object is a real entity (a patch, a weakness, a vendor, another
    CVE) stay as EDGES.

Standard library only.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CANONICAL = ROOT / "extraction_pipeline" / "canonical_kg"
OUT = Path(__file__).parent / "presentation_view.json"

PIVOTS = [
    "CVE-2026-33824", "CVE-2026-55040", "CVE-2026-59310",
    "CVE-2026-63520", "CVE-2026-65400",
]

# Literal-valued predicates -> node attributes.
AS_ATTRIBUTE = {
    "has baseScore": "cvss",
    "has baseSeverity": "severity",
    "has SSVC exploitation": "ssvc_exploitation",
    "has SSVC automatable": "ssvc_automatable",
    "has CISA action due date": "cisa_due_date",
    "has CISA exploit addition date": "cisa_added",
    "has EPSS probability": "epss",
}

# Entity-to-entity predicates -> graph edges.
AS_EDGE = {
    "has patch",
    "has weakness",
    "has vendor",
    "be chained to",
    "break",
    "observes",
}


def load_json(path: Path):
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def main() -> int:
    edges = load_json(CANONICAL / "edges.json")
    labels = {n["id"]: n["label"] for n in load_json(CANONICAL / "nodes.json")}

    nodes: dict[str, dict] = {}
    view_edges: list[dict] = []
    dropped: dict[str, int] = {}

    def touch(node_id: str) -> dict:
        if node_id not in nodes:
            label = labels.get(node_id, "")
            kind = "CVE" if any(p in label for p in PIVOTS) and label.startswith("CVE-") else "entity"
            nodes[node_id] = {"id": node_id, "label": label, "kind": kind, "attributes": {}}
        return nodes[node_id]

    for edge in edges:
        subject, obj = labels.get(edge["source"], ""), labels.get(edge["target"], "")
        if not any(p in subject + " " + obj for p in PIVOTS):
            continue
        predicate = edge["predicate_canonical"]

        if predicate in AS_ATTRIBUTE:
            node = touch(edge["source"])
            node["attributes"][AS_ATTRIBUTE[predicate]] = {
                "value": obj, "source_id": edge["source_id"], "evidence": edge["evidence"],
            }
        elif predicate in AS_EDGE:
            touch(edge["source"])
            touch(edge["target"])
            view_edges.append({
                "source": edge["source"], "target": edge["target"],
                "predicate": predicate,
                # Provenance travels with the projection: a slide claim stays auditable.
                "source_id": edge["source_id"], "evidence": edge["evidence"],
                "edge_id": edge["edge_id"],
            })
        else:
            dropped[predicate] = dropped.get(predicate, 0) + 1

    view = {
        "_note": "Projection of extraction_pipeline/canonical_kg for presentation (§11). "
                 "Generated by build_presentation_view.py -- do not edit by hand. Every edge "
                 "keeps the source_id and evidence of the canonical edge it projects.",
        "_rule": {
            "literal_predicates_become_attributes": sorted(AS_ATTRIBUTE),
            "entity_predicates_become_edges": sorted(AS_EDGE),
            "pivots": PIVOTS,
        },
        "_counts": {
            "nodes": len(nodes),
            "edges": len(view_edges),
            "canonical_nodes_total": len(labels),
            "canonical_edges_total": len(edges),
        },
        "_dropped_predicates": dict(sorted(dropped.items(), key=lambda kv: -kv[1])),
        "nodes": list(nodes.values()),
        "edges": view_edges,
    }
    OUT.write_text(json.dumps(view, indent=2, ensure_ascii=False), encoding="utf-8")

    print(f"nodes = {len(nodes)}  edges = {len(view_edges)}")
    print(f"  (brief §11 suggests 15-30 nodes / 20-50 relations)")
    print(f"  projected from {len(labels)} canonical nodes / {len(edges)} canonical edges")
    ok = 15 <= len(nodes) <= 30 and 20 <= len(view_edges) <= 50
    print(f"  within envelope: {'YES' if ok else 'NO'}")
    print(f"\ndropped predicate types (in scope, not projected): {len(dropped)}")
    for predicate, count in list(sorted(dropped.items(), key=lambda kv: -kv[1]))[:8]:
        print(f"    {count:>3}  {predicate}")
    print(f"\nwrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
